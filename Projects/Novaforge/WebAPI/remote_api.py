# NF2-8 — Crash-protection supervisor
# =============================================================================

def _run_supervised(host: str, port: int, max_retries: int = 20) -> None:
    """Launch the uvicorn server with auto-restart on crash.

    NF2-8
    """
    import subprocess

    attempt = 0
    backoff = 2.0

    while attempt < max_retries:
        print(
            f"[Novaforge WebAPI] Starting server (attempt {attempt + 1}/{max_retries}) "
            f"at http://{host}:{port}"
        )
        cmd = [
            sys.executable, "-m", "uvicorn",
            "Projects.Novaforge.WebAPI.remote_api:app",
            "--host", host, "--port", str(port),
        ]
        proc = subprocess.run(cmd, check=False)
        if proc.returncode == 0:
            print("[Novaforge WebAPI] Server exited cleanly.")
            break
        attempt += 1
        print(
            f"[Novaforge WebAPI] Server crashed (code {proc.returncode}). "
            f"Restarting in {backoff:.0f}s…"
        )
        time.sleep(backoff)
        backoff = min(backoff * 1.5, 60.0)

    if attempt >= max_retries:
        print(f"[Novaforge WebAPI] Giving up after {max_retries} crash restarts.")
        sys.exit(1)


