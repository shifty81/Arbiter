_TOKEN_FILE = _NF_ROOT / ".novaforge_api_token"


def _load_or_create_token() -> str:
    """Load the API token from disk, generating a new one if absent.

    NF2-5
    """
    if _TOKEN_FILE.exists():
        tok = _TOKEN_FILE.read_text(encoding="utf-8").strip()
        if tok:
            return tok
    tok = secrets.token_urlsafe(32)
    _TOKEN_FILE.write_text(tok + "\n", encoding="utf-8")
    _TOKEN_FILE.chmod(0o600)
    print(f"[Novaforge WebAPI] API token: {tok}")
    print(f"[Novaforge WebAPI] Token saved to: {_TOKEN_FILE}")
    return tok


_API_TOKEN: str = _load_or_create_token()


def _verify_token(
    creds: HTTPAuthorizationCredentials = Depends(HTTPBearer(auto_error=False)),
) -> None:
    """FastAPI dependency that enforces Bearer token auth.

    NF2-5
    """
    if creds is None or creds.credentials != _API_TOKEN:
        raise HTTPException(status_code=401, detail="Invalid or missing API token")


