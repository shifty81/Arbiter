def main() -> None:
    """Entry point for running the Novaforge Remote Web Interface.

    NF2-6
    """
    import argparse

    parser = argparse.ArgumentParser(description="Novaforge Remote Web Interface")
    parser.add_argument("--host",       default="0.0.0.0",  help="Bind host (default: 0.0.0.0)")
    parser.add_argument("--port",       default=8006, type=int, help="Port (default: 8006)")
    parser.add_argument("--supervised", action="store_true",
                        help="NF2-8: wrap server in auto-restart supervisor loop")
    parser.add_argument("--ngrok",      action="store_true",
                        help="NF2-6: open an ngrok tunnel (requires pyngrok)")
    args = parser.parse_args()

    if not _FASTAPI_OK:
        print(
            "[Novaforge WebAPI] FastAPI / uvicorn not installed.\n"
            "Run: pip install fastapi uvicorn[standard]"
        )
        sys.exit(1)

    print(f"[Novaforge WebAPI] API token: {_API_TOKEN}")
    print(f"[Novaforge WebAPI] Dashboard:  http://{args.host}:{args.port}/")

    # NF2-6: optional ngrok tunnel
    if args.ngrok:
        try:
            from pyngrok import ngrok  # type: ignore[import]
            tunnel = ngrok.connect(args.port)
            print(f"[Novaforge WebAPI] ngrok public URL: {tunnel.public_url}")
        except ImportError:
            print("[Novaforge WebAPI] pyngrok not installed — run: pip install pyngrok")

    if args.supervised:
        _run_supervised(args.host, args.port)
    else:
        uvicorn.run(
            "Projects.Novaforge.WebAPI.remote_api:app",
            host=args.host,
            port=args.port,
            reload=False,
        )


if __name__ == "__main__":
    main()
